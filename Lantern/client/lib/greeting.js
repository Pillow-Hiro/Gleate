// 時間帯の挨拶。
//
// **時計だけを見る。** 記録の有無・連続日数・前回いつ開いたかは、
// 一切材料にしない。
//
// 2026-08-12 に一度「入れない」と決めた。理由は
// 「時間帯で言葉を変えると、評価や勧誘に寄りやすい」。
// その懸念は**材料を時計だけに限れば起きない**。
// 危ないのは時間帯そのものではなく、「夜遅くまでお疲れさま」のように
// **時刻から相手の状態を推し量る**ことだった。
//
// だからここは分岐を3つしか持たず、どれも定型の挨拶に留める。
// 「お久しぶりです」「今日もお疲れさまです」の類は入れない
// （離脱期間を評価しない・頑張りを評価しない）。
//
// 深夜に専用の言葉を置かない。「まだ起きているんですね」は観察ではなく
// 詮索になる。23時も4時も「こんばんは」でよい。
//
// 端末の時計で判断する。サーバーの JST 判定（modules/timeutil.py）とは
// 別物で、揃える必要もない。挨拶は利用者のいる場所の時刻の話。
export function greetingFor(date = new Date()) {
  const hour = date.getHours()
  if (hour >= 5 && hour <= 10) return 'おはようございます'
  if (hour >= 11 && hour <= 16) return 'こんにちは'
  return 'こんばんは'
}
