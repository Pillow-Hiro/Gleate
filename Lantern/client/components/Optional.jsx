import { Component } from 'react'

// **添え物のせいで、道具が消えないようにする**（2026-09-05）。
//
// ## なぜ要ったか
//
// 実機で「キーボードの装飾がすべて消えている」と報告があった。
// 太字も、箇条書きも、写真も、全部。**書く道具が丸ごと消えた。**
//
// 変えたのは1つだけ——`SUGGESTIONS_READY` を `true` にして、
// Apple の「日記の候補」のビューを列に並べた。**それまで実機で
// 一度も描かれたことのない画面部品**で、描画に失敗すれば
// React は親ごと投げ捨てる。列全体がその巻き添えになる。
//
// ## 直し方を「原因を当てる」側に置かない
//
// 何が落ちているかは、手元では分からない（Xcode が無い）。
// **当てて直すと、当たったかどうかも分からない。**
//
// 代わりに構造を直す。**添え物は、消えてよい。道具は消えてはいけない。**
// この境目を型にした。中で何が起きても、外は生き残る。
//
// これは今回かぎりの当て木ではない。列に並ぶものは今後も増える。
// **増えるたびに全部を道連れにできる作りのほうが間違っている。**
//
// ## 黙って消えることについて
//
// 落ちたことは利用者に見せない。**見せても直せないものを見せない**
// ——押せるはずのものが無い、という状態は残るが、
// 「書けない」よりはるかにいい。記録には `console.warn` で残す。
export default class Optional extends Component {
  state = { fell: false }

  static getDerivedStateFromError() {
    return { fell: true }
  }

  componentDidCatch(error) {
    // **何が落ちたかを名前で残す。**次に実機の記録を見るとき、
    // ここが最初の手がかりになる
    console.warn(`[添え物] ${this.props.name || '名無し'} が落ちた`, error)
  }

  render() {
    if (this.state.fell) return null
    return this.props.children
  }
}
