import { View } from 'react-native'

// 余白の書き込み（2026-09-11・作者の指示「AIっぽさは無くしたいです」）。
//
// ## 色の付いた箱をやめた
//
// ここまで、Gleateの言葉は砂色の面に入れていた（`bg-ai-surface`）。
// **機械の返した言葉だけを色の付いた箱に入れる**——これは AI のアプリが
// どれもやっている形で、**配色を変えても構図のほうが残る。**
// 「色を変えたのに同じ顔に見える」のはここが理由だった。
//
// 箱をやめて、**左に1本の線**にした。地は本文と同じ色。
// 本の余白に誰かが書き込んでいる、という見え方になる。
//
// ## 灯り色は使わない
//
// 線を琥珀にすると、ホームでは `HomeCard` が3枚並ぶので
// `CLAUDE.md`「1画面に灯り色を2箇所以上置かない」に触れる。
// **この画面で琥珀に塗るのは今日の灯りだけ**という状態を崩さない。
//
// 線は `outline-variant`、字は呼ぶ側が `on-surface-variant` で渡す。
// **本文より一段退いて見えることで、書いた人の言葉と区別がつく。**
// 濃さの差だけで見分けさせるのではなく、**位置（字下げ）でも分ける。**
//
// ## 角丸を付けない
//
// 片側だけの線に角丸を付けると、線の端と角がずれて壊れて見える。
export default function MarginNote({ children, className = '' }) {
  return (
    <View className={`border-l-2 border-outline-variant pl-4 py-0.5 ${className}`}>
      {children}
    </View>
  )
}
