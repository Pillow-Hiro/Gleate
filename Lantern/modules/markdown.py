"""記録に含まれる Markdown の記法を剥がす。

**AI に渡す前に必ず通す。**

2026-08-13 に「やったこと」だけ装飾できるようにした。保存は Markdown で、
`**強い**` や `- 箇条書き` が本文に混ざる。そのまま AI に渡すと

- 記法が「その人の言葉」として扱われる
- 応答にも `**` が混ざる（AI憲法「Markdownを使わない」に反する）
- 頻出語に `**曲**` のような語が出る

扱うのは画面が出せる3つだけ。太字・斜体・箇条書き。
**見出しも表もリンクも扱わない。** 書けないものを剥がす必要はない。
"""
import re

# `**強い**` / `__強い__`
_BOLD = re.compile(r"\*\*(.+?)\*\*|__(.+?)__", re.S)
# `*斜め*` / `_斜め_`
# **`**` を先に処理すること。** 逆順だと `**a**` が `*` + `*a*` + `*` に割れる。
_ITALIC = re.compile(r"(?<!\*)\*(?!\*)(.+?)(?<!\*)\*(?!\*)|(?<!_)_(?!_)(.+?)(?<!_)_(?!_)", re.S)
# 行頭の `- ` `* ` `+ `
_BULLET = re.compile(r"^[ \t]*[-*+][ \t]+", re.M)


def strip_markdown(text):
    """記法を外して素のテキストにする。

    箇条書きの行頭記号は消すが、**改行は残す。**
    1行にまとめると、書いた人が分けた意味が失われる。
    """
    if not text:
        return ""
    out = _BOLD.sub(lambda m: m.group(1) or m.group(2) or "", text)
    out = _ITALIC.sub(lambda m: m.group(1) or m.group(2) or "", out)
    out = _BULLET.sub("", out)
    return out
